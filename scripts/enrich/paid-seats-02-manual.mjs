/**
 * 花火大会の有料観覧席の有無を入れる（一次情報を1件ずつ当たったぶん）
 *
 *   node scripts/enrich/paid-seats-02-manual.mjs
 *
 * `paid-seats-01-walker.mjs` はウォーカープラスの「有料席」欄を読むが、
 * **ウォーカープラスに載っていない花火大会が 298 件ある**（地域メディア由来のもの、
 * 自治体の発表から作ったものなど）。それを主催者のページで1件ずつ確かめる。
 *
 * ## `no` にしてよい条件
 *
 * **「有料席の記載が見つからない」は無いことの証明にならない。** 次のどれかが
 * 出典に書かれているときだけ `no` にする。
 *
 * 1. 「入場無料」「観覧無料」と明記されている
 * 2. 「有料観覧席は設けません」と明記されている
 * 3. 出典が項目として「有料席：なし」と持っている（ウォーカープラスの欄など）
 *
 * それ以外は `unknown` のままにする。**分からないものを無料と申告しない。**
 *
 * ## 料金は年を書く
 *
 * 料金は年ごとに変わるので、note には必ず「2026年は」と年を入れる。
 * 年の無い料金は、来年には誤情報になる。
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse, stringify } from 'yaml';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** id → ファイルの場所（重複統合でパスが動くので毎回作る） */
const index = new Map();
(function walk(d) {
  for (const e of readdirSync(d)) {
    const p = join(d, e);
    if (statSync(p).isDirectory()) walk(p);
    else if (e.endsWith('.yml')) index.set(e.slice(0, -4), p);
  }
})(join(ROOT, 'data', 'festivals'));

/** paid_seats と note、必要なら links を書き足す */
const set = (ids, value, note, link) => {
  for (const id of [].concat(ids)) {
    const p = index.get(id);
    if (!p) {
      console.log(`  ! ${id} が見つからない`);
      continue;
    }
    const f = parse(readFileSync(p, 'utf8'));
    let touched = false;
    if (f.paid_seats !== value || f.paid_seats_note !== note) {
      f.paid_seats = value;
      f.paid_seats_note = note;
      touched = true;
    }
    if (link) {
      const has = (f.links || []).some((l) => (typeof l === 'string' ? l : l?.url) === link.url);
      if (!has) {
        f.links = [...(f.links || []), link];
        touched = true;
      }
    }
    if (!touched) continue;
    writeFileSync(p, stringify(f, { lineWidth: 0 }), 'utf8');
    count[value] = (count[value] || 0) + 1;
  }
};
const count = {};

