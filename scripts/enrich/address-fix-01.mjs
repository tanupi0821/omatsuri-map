/**
 * 壊れた住所を直す（media / aggregator 由来のもの）
 *
 *   node scripts/enrich/address-fix-01.mjs
 *
 * `node scripts/audit-address.mjs` が見つけた壊れ方を直す。
 * **壊れた住所は、埋まっていないより悪い。** `下宮の内町1-18` で地図を引くと
 * 下関市ではない場所に落ちるので、祭りに行けない。
 *
 * 直し方の方針:
 *
 * - **住所は市区町村から書く**（都道府県は付けない）。
 *   `scripts/enrich/zz-normalize-address.mjs` が最後に揃えるが、最初からその形で入れる
 * - **掲載市区町村と住所が食い違うときは、出典の記事がどちらを言っているかで決める。**
 *   記事が正しければ住所を捨てる。住所が正しければ市区町村を直す
 * - **確かめられない住所は消す。** 別の場所を指す住所を残すより、空の方がまし
 *
 * このスクリプトは冪等（同じ値を書くだけ）で、名前を `address-` にして
 * `primary-*` より前・`zz-normalize-address.mjs` より前に流れるようにしてある。
 */
