// 黒石ねぷた祭り。号外NET/ご当地サイトの「青森市版」から取り込んだため
// `area.city` が青森市になっていたが、開催地は黒石市。
// このバケット（aomori/aomori-001）には既に黒石市の祭りが同居しているので、
// ファイルは動かさずに市区町村名だけ直す
const FIX_CITY = [
  ['aomori/aomori-001/aomori-001-gotouti-aomori-join-41438.yml', '黒石市'],
];
let fixed = 0;
for (const [rel, city] of FIX_CITY) {
  const p = join(ROOT, 'data', 'festivals', rel);
  let f;
  try {
    f = parse(readFileSync(p, 'utf8'));
  } catch {
    continue; // まだ作られていない/移動済み
  }
  if (f.area?.city === city) continue;
  f.area = { ...f.area, city };
  writeFileSync(p, stringify(f, { lineWidth: 0 }), 'utf8');
  fixed++;
  console.log(`  ${rel} の市区町村を ${city} に直した`);
}
console.log(`掲載市区町村の修正: ${fixed} 件`);
