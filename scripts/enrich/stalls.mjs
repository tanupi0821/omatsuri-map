/**
 * 屋台・露店の有無を一件ずつ確認して反映する
 *
 *   node scripts/enrich/stalls.mjs
 *
 * **同じ神社でも祭りによって性格がまったく違う。**
 * 馬絹神社（川崎市宮前区）は 7月14日の夏季大祭が神事中心なのに対し、
 * 10月15日の秋季例大祭は神輿が地区を巡行し多くの露店が出る。
 * 「祭りに行こう」と思って調べる人にとっては、この差が最も知りたいこと。
 *
 * 神社庁から一括で取り込んだ例大祭は例祭日しか分からないので既定は unknown。
 * ここで一件ずつ裏を取って yes / no に上げていく。
 *
 * 調べ方:
 *  1. 「<神社名> 例大祭 露店」「<神社名> 祭り 屋台」で検索
 *  2. 神社公式・地域メディア・区役所のページで露店の記述を確認
 *  3. 確認できたものだけ yes。書いていないものは unknown のままにする
 *     （「書いていない＝出ない」ではないので no にはしない）
 */
