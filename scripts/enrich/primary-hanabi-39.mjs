// 開始日から終了日までの毎日を並べる（毎晩やる祭り用）
const everyDay = (from, to) => {
  const out = [];
  for (let d = new Date(from); d <= new Date(to); d.setDate(d.getDate() + 1)) {
    out.push(d.toISOString().slice(0, 10));
  }
  return out;
};

