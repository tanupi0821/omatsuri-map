/**
 * 一次情報での裏取り（第59弾：期間ものと連続開催の切り分け）
 *
 *   node scripts/enrich/primary-hanabi-59.mjs
 *
 * 「日付が2つで間隔が3日以上」でも、**中身は3通りある**。
 *
 * A. 連続開催の中日が落ちている（博多夏祭り 7/10〜14 など）→ 全日を入れる
 * B. 期間ものの始まりと終わり（うえの夏まつり 7/10〜8/11、
 *    いたばし絵本とデザインフェスティバル 7/18〜8/16）→ **2日のままで正しい**
 * C. 飛び飛びの複数回（おまち神楽まつり 7/4・11 の土曜2回）→ **2日のままで正しい**
 *
 * B と C を無理に日付で埋めると、**開催していない日を開催日として出す**ことになる。
 * 逆に何も書かないと次に洗う人が同じ確認を繰り返すので、
 * **「2日で正しい理由」を note に残す**のがこの作業の落とし所。
 */
import { patchAll } from '../import/_lib.mjs';

const CHECKED = '2026-08-06';

const everyDay = (from, to) => {
  const out = [];
  for (let d = new Date(from); d <= new Date(to); d.setDate(d.getDate() + 1)) {
    out.push(d.toISOString().slice(0, 10));
  }
  return out;
};

